def reverse_approx(lat: float, lng: float) -> Optional[Dict[str, Any]]:
    try:
        lat_f, lng_f = float(lat), float(lng)
    except Exception:
        return None
    for name, address, la0, la1, ln0, ln1 in _BOXES:
        if la0 <= lat_f <= la1 and ln0 <= lng_f <= ln1:
            return {
                "name": name,
                "address": address,
                "lat": lat_f,
                "lng": lng_f,
                "approx": True,
            }
    return {
        "name": "选中位置",
        "address": f"{lat_f:.5f}, {lng_f:.5f}",
        "lat": lat_f,
        "lng": lng_f,
        "approx": True,
    }
